/**
 * Generate the bundled BYOK docs index (Phase 7.7) from the curated
 * Markdown subset in `src/AiGeneration/Byok/docs/gdevelop-docs/`:
 *
 *   cd newIDE/app/scripts
 *   node generate-byok-docs-index.js
 *
 * The `.md` files are the source of truth (copied from the
 * GDevelop-documentation repository — see Byok/docs/ABOUT.md); this script
 * emits a committed ES module the app imports without a webpack
 * raw-loader. Re-run it after refreshing the subset, and commit both.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const docsRoot = path.resolve(
  __dirname,
  '..',
  'src',
  'AiGeneration',
  'Byok',
  'docs',
  'gdevelop-docs'
);
const outputPath = path.join(docsRoot, 'BundledDocs.generated.js');

/** The first `# ` heading of a Markdown file, or its file name. */
const extractTitle = (content, fileName) => {
  const heading = /^#\s+(.+)$/m.exec(content);
  return heading ? heading[1].trim() : fileName;
};

/** Every Markdown heading (its level and text), for the search index. */
const extractHeadings = content => {
  const headings = [];
  for (const line of content.split('\n')) {
    const match = /^(#{1,6})\s+(.+)$/.exec(line);
    if (match) headings.push(match[2].trim());
  }
  return headings;
};

const collectMarkdownFiles = (directory, prefix) => {
  const files = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...collectMarkdownFiles(entryPath, `${prefix}${entry.name}/`));
      continue;
    }
    if (entry.isFile() && entry.name.endsWith('.md')) {
      files.push(`${prefix}${entry.name}`);
    }
  }
  return files.sort();
};

const generateDocsIndex = () => {
  const paths = collectMarkdownFiles(docsRoot, '');
  const pages = paths.map(relativePath => {
    const content = fs.readFileSync(path.join(docsRoot, relativePath), 'utf8');
    return {
      path: relativePath,
      title: extractTitle(content, path.basename(relativePath, '.md')),
      headings: extractHeadings(content),
      content,
    };
  });

  const moduleBody = `// @flow
//
// GENERATED by scripts/generate-byok-docs-index.js — do not edit by hand.
// Refresh the curated .md subset (see Byok/docs/ABOUT.md), then re-run the
// generator. This module exists so the app can ship the bundled docs
// without a webpack raw-loader.

export type ByokBundledDocPage = {|
  path: string,
  title: string,
  headings: Array<string>,
  content: string,
|};

const byokBundledDocPages: Array<ByokBundledDocPage> = ${JSON.stringify(
    pages,
    null,
    2
  )};

export default byokBundledDocPages;
`;

  fs.writeFileSync(outputPath, moduleBody);
  console.log(
    `Bundled docs index written: ${pages.length} page(s) -> ${path.relative(
      process.cwd(),
      outputPath
    )}`
  );
};

generateDocsIndex();
