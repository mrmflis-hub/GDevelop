/**
 * Generate the BYOK builtin skills index (Phase 7.6) from the Markdown
 * sources in `src/AiGeneration/Byok/Skills/*.md`:
 *
 *   cd newIDE/app/scripts
 *   node generate-byok-skills-index.js
 *
 * The `.md` files are the editable source of truth; this script emits a
 * committed ES module (`Byok/Skills/ByokBuiltinSkills.generated.js`) the
 * app can import without a webpack raw-loader. Re-run it after editing any
 * skill, and commit both together.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const skillsRoot = path.resolve(__dirname, '..', 'src', 'AiGeneration', 'Byok', 'Skills');
const outputPath = path.join(skillsRoot, 'ByokBuiltinSkills.generated.js');

const generateSkillsIndex = () => {
  const skillFiles = fs
    .readdirSync(skillsRoot, { withFileTypes: true })
    .filter(
      entry =>
        entry.isFile() &&
        entry.name.endsWith('.md') &&
        !entry.name.startsWith('README')
    )
    .map(entry => entry.name)
    .sort();

  const entries = skillFiles.map(fileName => ({
    fileName,
    content: fs.readFileSync(path.join(skillsRoot, fileName), 'utf8'),
  }));

  const moduleBody = `// @flow
//
// GENERATED by scripts/generate-byok-skills-index.js — do not edit by hand.
// Edit the sibling .md skill files, then re-run the generator.
// This module exists so the app can ship the builtin BYOK skills without a
// webpack raw-loader (the .md files stay the source of truth).

export type ByokBuiltinSkillEntry = {| fileName: string, content: string |};

const byokBuiltinSkillEntries: Array<ByokBuiltinSkillEntry> = ${JSON.stringify(
    entries,
    null,
    2
  )};

export default byokBuiltinSkillEntries;
`;

  fs.writeFileSync(outputPath, moduleBody);
  console.log(
    `Builtin skills index written: ${entries.length} skill(s) -> ${path.relative(
      process.cwd(),
      outputPath
    )}`
  );
};

generateSkillsIndex();
